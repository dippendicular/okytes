//! Deterministic hyper fault server. Content is generated per 64 KiB frame,
//! keeping server memory independent of logical file size. Request history is
//! capped; connection tasks are aborted on shutdown.
use bytes::Bytes;
use futures::stream;
use http_body_util::{combinators::UnsyncBoxBody, BodyExt, Empty, StreamBody};
use hyper::{body::Frame, server::conn::http1, service::service_fn, Method, Request, Response};
use hyper_util::rt::TokioIo;
use sha2::{Digest, Sha256};
use std::{
    collections::HashMap,
    convert::Infallible,
    net::{IpAddr, SocketAddr},
    sync::{
        atomic::{AtomicU64, AtomicUsize, Ordering},
        Arc, Mutex,
    },
    time::Duration,
};
use tokio::{net::TcpListener, sync::oneshot, task::JoinHandle};

type Body = UnsyncBoxBody<Bytes, std::io::Error>;
/// Parameters for deterministic generated content and response pacing.
#[derive(Clone, Debug)]
pub struct ServerConfig {
    /// Logical size; no full-file allocation is performed.
    pub file_size: usize,
    /// Seed changes generated byte content.
    pub seed: u64,
    /// Delay per body frame for slow-transfer/control tests.
    pub frame_delay: Duration,
    /// Delay before each response's headers (including probes).
    pub latency: Duration,
    /// Per-client-IP payload cap. Null is unlimited; pacing has no burst.
    pub bandwidth_bps: Option<u64>,
    /// Independent payload cap for each response body.
    pub connection_bps: Option<u64>,
    /// Reject bodies above this per-client-IP concurrency with 429 and Retry-After: 1.
    pub max_active: Option<usize>,
    /// Reset every Nth body halfway through; zero disables injection.
    pub disconnect_every: usize,
}
impl Default for ServerConfig {
    fn default() -> Self {
        Self {
            file_size: 1024 * 1024,
            seed: 42,
            frame_delay: Duration::ZERO,
            latency: Duration::ZERO,
            bandwidth_bps: None,
            connection_bps: None,
            max_active: None,
            disconnect_every: 0,
        }
    }
}
/// Bounded request observation for protocol assertions.
#[derive(Clone, Debug)]
pub struct ObservedRequest {
    /// Session presence only; credential values are never retained in history.
    pub has_session: bool,
    /// Received path.
    pub path: String,
    /// Received If-Range value.
    pub if_range: Option<String>,
    /// Received Range value.
    pub range: Option<String>,
}
struct State {
    fixtures: Mutex<HashMap<String, Bytes>>,
    config: ServerConfig,
    version: AtomicU64,
    requests: Mutex<Vec<ObservedRequest>>,
    gets: AtomicUsize,
    throttles: AtomicUsize,
    active: AtomicUsize,
    peak: AtomicUsize,
    pacing: tokio::sync::Mutex<HashMap<IpAddr, tokio::time::Instant>>,
    clients: Mutex<HashMap<IpAddr, usize>>,
}
struct Active(Arc<State>, IpAddr);
impl Drop for Active {
    fn drop(&mut self) {
        self.0.active.fetch_sub(1, Ordering::SeqCst);
        if let Ok(mut clients) = self.0.clients.lock() {
            if let Some(count) = clients.get_mut(&self.1) {
                *count = count.saturating_sub(1);
                if *count == 0 {
                    clients.remove(&self.1);
                }
            }
        }
    }
}

/// Running local server; shutdown also closes all accepted connections.
pub struct TestServer {
    /// Bound loopback address.
    pub addr: SocketAddr,
    /// SHA-256 of generated content, computed with bounded memory.
    pub content_hash: String,
    /// Initial strong validator.
    pub etag: String,
    state: Arc<State>,
    shutdown: Option<oneshot::Sender<()>>,
    handle: JoinHandle<()>,
}
impl TestServer {
    /// Add or replace a bounded synthetic media fixture (8 MiB each, 128 total).
    pub fn fixture(&self, path: &str, bytes: impl Into<Bytes>) -> std::io::Result<()> {
        let bytes = bytes.into();
        if bytes.len() > 8 * 1024 * 1024 || !path.starts_with("/fixtures/") {
            return Err(std::io::Error::other("invalid fixture bounds"));
        }
        let mut fixtures = self
            .state
            .fixtures
            .lock()
            .map_err(|_| std::io::Error::other("fixture lock failed"))?;
        if fixtures.len() >= 128 && !fixtures.contains_key(path) {
            return Err(std::io::Error::other("fixture count bound"));
        }
        fixtures.insert(path.into(), bytes);
        Ok(())
    }
    /// Bind loopback and launch a deterministic server.
    pub async fn start(config: ServerConfig) -> Result<Self, std::io::Error> {
        let listener = TcpListener::bind("127.0.0.1:0").await?;
        let addr = listener.local_addr()?;
        let mut hash = Sha256::new();
        let mut offset = 0;
        while offset < config.file_size {
            let len = (config.file_size - offset).min(65536);
            hash.update(content(offset, len, config.seed));
            offset += len;
        }
        let content_hash = format!("{:x}", hash.finalize());
        let etag = "\"version-1\"".to_owned();
        let state = Arc::new(State {
            fixtures: Mutex::new(HashMap::new()),
            config,
            version: AtomicU64::new(1),
            requests: Mutex::new(vec![]),
            gets: AtomicUsize::new(0),
            throttles: AtomicUsize::new(0),
            active: AtomicUsize::new(0),
            peak: AtomicUsize::new(0),
            pacing: tokio::sync::Mutex::new(HashMap::new()),
            clients: Mutex::new(HashMap::new()),
        });
        let (shutdown, mut stop) = oneshot::channel();
        let shared = state.clone();
        let handle = tokio::spawn(async move {
            let mut connections = tokio::task::JoinSet::new();
            loop {
                tokio::select! {
                    _=&mut stop=>break,
                    Some(_)=connections.join_next(),if !connections.is_empty()=>{},
                    connection=listener.accept()=>{
                        let Ok((socket,peer))=connection else {break};
                        if connections.len()>=512 {drop(socket);continue;}
                        let state=shared.clone();
                        connections.spawn(async move {
                            let service=service_fn(move |req|handle_request(req,state.clone(),peer.ip()));
                            let _=http1::Builder::new().serve_connection(TokioIo::new(socket),service).await;
                        });
                    }
                }
            }
            connections.abort_all();
            while connections.join_next().await.is_some() {}
        });
        Ok(Self {
            addr,
            content_hash,
            etag,
            state,
            shutdown: Some(shutdown),
            handle,
        })
    }
    /// Form a URL to a fault endpoint.
    pub fn url(&self, path: &str) -> String {
        format!("http://{}{path}", self.addr)
    }
    /// Change remote version and generated body seed for resume tests.
    pub fn set_version(&self, version: u64) {
        self.state.version.store(version, Ordering::SeqCst);
    }
    /// Snapshot bounded request observations.
    pub fn requests(&self) -> Vec<ObservedRequest> {
        self.state
            .requests
            .lock()
            .map(|r| r.clone())
            .unwrap_or_default()
    }
    /// Maximum simultaneously active response bodies.
    pub fn peak_connections(&self) -> usize {
        self.state.peak.load(Ordering::SeqCst)
    }
    /// Stop the listener and accepted connections.
    pub async fn shutdown(mut self) {
        if let Some(stop) = self.shutdown.take() {
            let _ = stop.send(());
        }
        let _ = (&mut self.handle).await;
    }
}
impl Drop for TestServer {
    fn drop(&mut self) {
        if let Some(stop) = self.shutdown.take() {
            let _ = stop.send(());
        }
        self.handle.abort();
    }
}
fn content(offset: usize, len: usize, seed: u64) -> Vec<u8> {
    let pattern: Vec<_> = (0..256)
        .map(|i| (i as u8).wrapping_add((offset as u8).wrapping_add(seed as u8)))
        .collect();
    let mut bytes = vec![0; len];
    for chunk in bytes.chunks_mut(256) {
        chunk.copy_from_slice(&pattern[..chunk.len()]);
    }
    bytes
}
fn empty() -> Body {
    Empty::<Bytes>::new()
        .map_err(|never: Infallible| match never {})
        .boxed_unsync()
}
fn response(status: u16, headers: Vec<(&str, String)>, body: Body) -> Response<Body> {
    let mut response = Response::new(body);
    if let Ok(status) = hyper::StatusCode::from_u16(status) {
        *response.status_mut() = status;
    }
    for (key, value) in headers {
        if let (Ok(key), Ok(value)) = (
            hyper::header::HeaderName::from_bytes(key.as_bytes()),
            hyper::header::HeaderValue::from_str(&value),
        ) {
            response.headers_mut().insert(key, value);
        }
    }
    response
}
async fn handle_request(
    req: Request<hyper::body::Incoming>,
    state: Arc<State>,
    client: IpAddr,
) -> Result<Response<Body>, Infallible> {
    if !state.config.latency.is_zero() {
        tokio::time::sleep(state.config.latency).await;
    }
    let path = req.uri().path().to_owned();
    let range = req
        .headers()
        .get("range")
        .and_then(|v| v.to_str().ok())
        .map(str::to_owned);
    let if_range = req
        .headers()
        .get("if-range")
        .and_then(|v| v.to_str().ok())
        .map(str::to_owned);
    if let Ok(mut requests) = state.requests.lock() {
        if requests.len() < 1024 {
            requests.push(ObservedRequest {
                has_session: req.headers().contains_key("cookie")
                    || req.headers().contains_key("authorization"),
                path: path.clone(),
                range: range.clone(),
                if_range: if_range.clone(),
            });
        }
    }
    if path.starts_with("/fixtures/") {
        let bytes = state
            .fixtures
            .lock()
            .ok()
            .and_then(|fixtures| fixtures.get(&path).cloned());
        let Some(bytes) = bytes else {
            return Ok(response(404, vec![], empty()));
        };
        let etag = format!("\"{:x}\"", Sha256::digest(&bytes));
        let mut headers = vec![("etag", etag.clone()), ("accept-ranges", "bytes".into())];
        let total = bytes.len();
        let mut status = 200;
        let mut data = bytes;
        if let Some(ref range) = range {
            if if_range.as_ref().is_none_or(|value| value == &etag) {
                let Some((start, end)) = parse_range(range, total) else {
                    return Ok(response(416, vec![], empty()));
                };
                data = data.slice(start..=end);
                status = 206;
                headers.push(("content-range", format!("bytes {start}-{end}/{total}")));
            }
        }
        headers.push(("content-length", data.len().to_string()));
        let body = if req.method() == Method::HEAD {
            empty()
        } else {
            let delay = state.config.frame_delay;
            StreamBody::new(stream::unfold(
                (data, 0usize),
                move |(data, offset)| async move {
                    if offset >= data.len() {
                        return None;
                    }
                    if !delay.is_zero() {
                        tokio::time::sleep(delay).await;
                    }
                    let end = data.len().min(offset + 8192);
                    let frame = Frame::data(data.slice(offset..end));
                    Some((Ok::<_, std::io::Error>(frame), (data, end)))
                },
            ))
            .boxed_unsync()
        };
        return Ok(response(status, headers, body));
    }
    if path == "/redirect" {
        return Ok(response(302, vec![("location", "/normal".into())], empty()));
    }
    if path == "/cross-origin" {
        if let Some(target) = req
            .uri()
            .query()
            .and_then(|query| query.strip_prefix("to="))
        {
            return Ok(response(302, vec![("location", target.into())], empty()));
        }
    }
    if path == "/browser-page" {
        let html = Bytes::from_static(b"<!doctype html><html><title>Okytes browser fixture</title><body><a id='auto' href='/browser-auto.zip' download>Automatic download</a><a id='fallback' href='/fallback.zip' download>Fallback download</a><a href='/sample.m3u8'>Manifest candidate</a></body></html>");
        let body = http_body_util::Full::new(html)
            .map_err(|never: Infallible| match never {})
            .boxed_unsync();
        return Ok(response(
            200,
            vec![("content-type", "text/html; charset=utf-8".into())],
            body,
        ));
    }
    if path == "/expired" {
        return Ok(response(403, vec![], empty()));
    }
    if path == "/session-protected"
        && (!req.headers().contains_key("cookie") || !req.headers().contains_key("authorization"))
    {
        return Ok(response(403, vec![], empty()));
    }
    if path == "/head-unsupported" && req.method() == Method::HEAD {
        return Ok(response(405, vec![], empty()));
    }
    if matches!(path.as_str(), "/throttle-429" | "/throttle-503")
        && state.throttles.fetch_add(1, Ordering::SeqCst) < 2
    {
        return Ok(response(
            if path.ends_with("429") { 429 } else { 503 },
            vec![("retry-after", "1".into())],
            empty(),
        ));
    }
    if path == "/high-latency" {
        tokio::time::sleep(Duration::from_millis(100)).await;
    }
    let version = state.version.load(Ordering::SeqCst);
    let etag = if path == "/weak-etag" {
        "W/\"weak\"".to_owned()
    } else if path == "/changed-etag" && req.method() != Method::HEAD {
        "\"version-2\"".into()
    } else {
        format!("\"version-{version}\"")
    };
    let total = state.config.file_size;
    let mut start = 0;
    let mut end = total;
    let mut status = 200;
    if let Some(range) = &range {
        if path != "/range-ignored"
            && path != "/no-range"
            && if_range.as_ref().is_none_or(|v| v == &etag)
        {
            if let Some((a, b)) = parse_range(range, total) {
                start = a;
                end = b + 1;
                status = 206;
            } else {
                return Ok(response(416, vec![], empty()));
            }
        }
    }
    let mut headers = vec![
        ("content-type", "application/octet-stream".into()),
        ("etag", etag),
        ("last-modified", "Wed, 14 Oct 2026 00:00:00 GMT".into()),
    ];
    if path == "/missing-etag" && version > 1 {
        headers.retain(|(name, _)| *name != "etag");
    }
    if path == "/changed-modified" {
        for (name, value) in &mut headers {
            if *name == "etag" {
                *value = "\"version-1\"".into();
            }
            if *name == "last-modified" && version > 1 {
                *value = "Thu, 15 Oct 2026 00:00:00 GMT".into();
            }
        }
    }
    if path == "/disposition" {
        headers.push((
            "content-disposition",
            "attachment; filename=\"../../CON.txt\"".into(),
        ));
    }
    if path != "/no-range" {
        headers.push(("accept-ranges", "bytes".into()));
    }
    if path != "/chunked" {
        headers.push((
            "content-length",
            if path == "/wrong-content-length" {
                (end - start + 100).to_string()
            } else {
                (end - start).to_string()
            },
        ));
    }
    if status == 206 {
        headers.push((
            "content-range",
            if path == "/invalid-headers" {
                "bytes garbage".into()
            } else if path == "/wrong-range" {
                format!("bytes {}-{}/{total}", start + 1, end - 1)
            } else {
                format!("bytes {start}-{}/{total}", end - 1)
            },
        ));
    }
    if req.method() == Method::HEAD {
        return Ok(response(status, headers, empty()));
    }
    {
        let Ok(mut clients) = state.clients.lock() else {
            return Ok(response(503, vec![], empty()));
        };
        let count = clients.entry(client).or_default();
        if state.config.max_active.is_some_and(|cap| *count >= cap) {
            return Ok(response(429, vec![("retry-after", "1".into())], empty()));
        }
        *count += 1;
    }
    let active = state.active.fetch_add(1, Ordering::SeqCst) + 1;
    let get = state.gets.fetch_add(1, Ordering::SeqCst);
    let disconnect = (path == "/mid-disconnect" && get == 0)
        || (state.config.disconnect_every > 0
            && (get + 1).is_multiple_of(state.config.disconnect_every));
    let corrupt = path == "/corrupted";
    let delay = if path == "/accelerating" {
        if get < 2 {
            Duration::from_millis(60)
        } else {
            Duration::from_millis(5)
        }
    } else if path == "/slow" {
        state.config.frame_delay.max(Duration::from_millis(10))
    } else {
        state.config.frame_delay
    };
    state.peak.fetch_max(active, Ordering::SeqCst);
    let guard = Active(state.clone(), client);
    let pacing = state.clone();
    let seed = state.config.seed + version - 1;
    let midpoint = start + (end - start) / 2;
    let body = stream::unfold(
        (start, Some(guard), false),
        move |(offset, guard, failed)| {
            let pacing = pacing.clone();
            async move {
                if offset >= end || failed {
                    return None;
                }
                if !delay.is_zero() {
                    tokio::time::sleep(delay).await;
                }
                if disconnect && offset >= midpoint {
                    return Some((
                        Err(std::io::Error::new(
                            std::io::ErrorKind::ConnectionReset,
                            "injected disconnect",
                        )),
                        (offset, guard, true),
                    ));
                }
                let len = (end - offset).min(65536);
                if let Some(rate) = pacing.config.connection_bps {
                    tokio::time::sleep(Duration::from_secs_f64(len as f64 / rate.max(1) as f64))
                        .await;
                }
                if let Some(rate) = pacing.config.bandwidth_bps {
                    let deadline = {
                        let mut clocks = pacing.pacing.lock().await;
                        let now = tokio::time::Instant::now();
                        clocks.retain(|_, deadline| *deadline > now);
                        let clock = clocks.entry(client).or_insert(now);
                        *clock = (*clock).max(now)
                            + Duration::from_secs_f64(len as f64 / rate.max(1) as f64);
                        *clock
                    };
                    tokio::time::sleep_until(deadline).await;
                }
                let mut bytes = content(offset, len, seed);
                if corrupt && !bytes.is_empty() {
                    bytes[0] ^= 0xff;
                }
                Some((
                    Ok(Frame::data(Bytes::from(bytes))),
                    (offset + len, guard, false),
                ))
            }
        },
    );
    Ok(response(
        status,
        headers,
        StreamBody::new(body).boxed_unsync(),
    ))
}
fn parse_range(value: &str, total: usize) -> Option<(usize, usize)> {
    let (a, b) = value.strip_prefix("bytes=")?.split_once('-')?;
    let a: usize = a.parse().ok()?;
    let b: usize = if b.is_empty() {
        total.checked_sub(1)?
    } else {
        b.parse().ok()?
    };
    (a <= b && b < total).then_some((a, b))
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn empty_range_is_rejected() {
        assert_eq!(parse_range("bytes=0-", 0), None);
    }
    #[tokio::test]
    async fn server_lifecycle() {
        let server = TestServer::start(ServerConfig::default()).await.unwrap();
        assert_eq!(server.content_hash.len(), 64);
        server.shutdown().await;
    }
    #[tokio::test]
    async fn connection_penalty_is_per_ip_not_shared_across_clients() {
        let server = TestServer::start(ServerConfig {
            file_size: 256 * 1024,
            max_active: Some(1),
            frame_delay: Duration::from_millis(100),
            ..Default::default()
        })
        .await
        .unwrap();
        let first = reqwest::Client::builder()
            .local_address(Some("127.0.0.1".parse::<IpAddr>().unwrap()))
            .build()
            .unwrap();
        let other = reqwest::Client::builder()
            .local_address(Some("127.0.0.2".parse::<IpAddr>().unwrap()))
            .build()
            .unwrap();
        let held = first.get(server.url("/normal")).send().await.unwrap();
        assert_eq!(held.status(), 200);
        assert_eq!(
            first
                .get(server.url("/normal"))
                .send()
                .await
                .unwrap()
                .status(),
            429
        );
        let separate = other.get(server.url("/normal")).send().await.unwrap();
        assert_eq!(separate.status(), 200);
        assert_eq!(held.bytes().await.unwrap().len(), 256 * 1024);
        assert_eq!(separate.bytes().await.unwrap().len(), 256 * 1024);
    }
}
